import type { DailyData, AlertItem } from '@/types';

const generateAlerts = (data: Omit<DailyData, 'alerts'>): AlertItem[] => {
  const alerts: AlertItem[] = [];
  
  const revenueRate = (data.revenue.total / data.revenue.target) * 100;
  alerts.push({
    key: 'revenue',
    name: '营收达成率',
    value: revenueRate,
    threshold: { key: 'revenue', name: '营收达成率', value: revenueRate, warning: 80, danger: 60, isNegative: false },
    level: revenueRate < 60 ? 'red' : revenueRate < 80 ? 'yellow' : 'green',
    link: '/revenue/total',
  });

  alerts.push({
    key: 'foodCost',
    name: '食材成本率',
    value: data.foodCost.rate,
    threshold: { key: 'foodCost', name: '食材成本率', value: data.foodCost.rate, warning: 31, danger: 33, isNegative: true },
    level: data.foodCost.rate > 33 ? 'red' : data.foodCost.rate > 31 ? 'yellow' : 'green',
    link: '/food-cost',
  });

  alerts.push({
    key: 'laborEfficiency',
    name: '人效',
    value: data.hr.laborEfficiency,
    threshold: { key: 'laborEfficiency', name: '人效', value: data.hr.laborEfficiency, warning: 8000, danger: 6000, isNegative: false },
    level: data.hr.laborEfficiency < 6000 ? 'red' : data.hr.laborEfficiency < 8000 ? 'yellow' : 'green',
    link: '/hr/labor',
  });

  alerts.push({
    key: 'kitchenTime',
    name: '出餐时长',
    value: data.kitchen.avgTime,
    threshold: { key: 'kitchenTime', name: '出餐时长', value: data.kitchen.avgTime, warning: 16, danger: 20, isNegative: true },
    level: data.kitchen.avgTime > 20 ? 'red' : data.kitchen.avgTime > 16 ? 'yellow' : 'green',
    link: '/kitchen',
  });

  alerts.push({
    key: 'soldOut',
    name: '沽清率',
    value: data.soldOut.rate,
    threshold: { key: 'soldOut', name: '沽清率', value: data.soldOut.rate, warning: 4, danger: 6, isNegative: true },
    level: data.soldOut.rate > 6 ? 'red' : data.soldOut.rate > 4 ? 'yellow' : 'green',
    link: '/sold-out',
  });

  alerts.push({
    key: 'inventory',
    name: '库存周转率',
    value: data.inventory.turnoverRate,
    threshold: { key: 'inventory', name: '库存周转率', value: data.inventory.turnoverRate, warning: 4, danger: 3, isNegative: false },
    level: data.inventory.turnoverRate < 3 ? 'red' : data.inventory.turnoverRate < 4 ? 'yellow' : 'green',
    link: '/inventory',
  });

  alerts.push({
    key: 'training',
    name: '训练率',
    value: data.hr.trainingRate,
    threshold: { key: 'training', name: '训练率', value: data.hr.trainingRate, warning: 60, danger: 40, isNegative: false },
    level: data.hr.trainingRate < 40 ? 'red' : data.hr.trainingRate < 60 ? 'yellow' : 'green',
    link: '/hr/training',
  });

  alerts.push({
    key: 'turnover',
    name: '离职率',
    value: data.hr.turnoverRate,
    threshold: { key: 'turnover', name: '离职率', value: data.hr.turnoverRate, warning: 10, danger: 15, isNegative: true },
    level: data.hr.turnoverRate > 15 ? 'red' : data.hr.turnoverRate > 10 ? 'yellow' : 'green',
    link: '/hr/turnover',
  });

  return alerts;
};

